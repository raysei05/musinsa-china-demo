// Keep the browser's demo products in sync with the AI's catalog.
import {readFileSync,writeFileSync} from 'node:fs';
const catalog=JSON.parse(readFileSync(new URL('../lib/catalog.json',import.meta.url),'utf8'));
const extra=catalog.filter(p=>p.id>=16&&p.id<100).map(({visualDescription,...p})=>p);
const photos=Object.fromEntries(catalog.map(p=>[p.id,`/assets/products/${p.id}.webp`]));
writeFileSync(new URL('../public/catalog.js',import.meta.url),`// Generated by scripts/sync-catalog.mjs\nproducts.push(...${JSON.stringify(extra)});\nObject.assign(extraProductPhotos,${JSON.stringify(photos)});\n`);
